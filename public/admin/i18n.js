const patterns = [...NL.entries()]
  .filter(([key]) => key.includes('{'))
  .map(([key, value]) => ({
    expression: new RegExp(`^${key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\\\{[^}]+\\\}/g, '(.+?)')}$`),
    value
  }));
let language = 'nl';

export function setLanguage(next) {
  language = next === 'en' ? 'en' : 'nl';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language;
    document.title = language === 'nl' ? 'Make It So — Beheer' : 'Make It So — Admin';
  }
}

export function translateText(value) {
  if (language === 'en') return value;
  if (NL.has(value)) return NL.get(value);
  for (const { expression, value: translation } of patterns) {
    const match = value.match(expression);
    if (!match) continue;
    let index = 1;
    return translation.replace(/\{[^}]+\}/g, () => match[index++]);
  }
  return value;
}

export function translateMarkup(markup) {
  if (language === 'en') return markup;
  const decode = (value) => value
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'");
  const encode = (value) => value
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  const translateNode = (value) => {
    const decoded = decode(value);
    const trimmed = decoded.trim().replace(/\s+/g, ' ');
    if (!trimmed) return value;
    const translated = translateText(trimmed);
    if (translated === trimmed) return value;
    const leading = decoded.match(/^\s*/)[0];
    const trailing = decoded.match(/\s*$/)[0];
    return encode(leading + translated + trailing);
  };
  return markup
    .replace(/(<[^>]*>)|([^<]+)/g, (part, tag, text) => tag ? tag : translateNode(text))
    .replace(/\b(aria-label|placeholder|title|alt)="([^"]*)"/g, (attribute, name, value) =>
      `${name}="${encode(translateText(decode(value)))}"`);
}

